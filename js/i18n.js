const LOCALE_KEY = "portfolio-locale";
const THEME_KEY = "portfolio-theme";

const LOGO_SRC = {
  vs: { light: "assets/LogoC-VS.png", dark: "assets/LogoE-VS.png" },
  dl: { light: "assets/LogoC-DL.png", dark: "assets/LogoE-DL.png" },
  sudra: { light: "assets/sudra-lockup-light.svg", dark: "assets/sudra-lockup-dark.svg" },
  "sudra-icon": { light: "assets/sudra-icon-light.svg", dark: "assets/sudra-icon-dark.svg" },
};

function getLocale() {
  const stored = localStorage.getItem(LOCALE_KEY);
  if (stored === "pt" || stored === "en") return stored;
  return "pt";
}

function t(key, locale = getLocale()) {
  return I18N[locale]?.[key] ?? I18N.pt[key] ?? key;
}

function applyI18n(locale) {
  document.documentElement.lang = locale === "en" ? "en" : "pt-BR";
  document.title = t("meta.title", locale);
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", t("meta.description", locale));
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.setAttribute("content", t("meta.title", locale));
  const ogSite = document.querySelector('meta[property="og:site_name"]');
  if (ogSite) ogSite.setAttribute("content", t("brand.name", locale));
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc) {
    ogDesc.setAttribute(
      "content",
      locale === "en"
        ? "Websites, order systems, ERP/CRM, scheduling, and custom software by SUDRA Technologies."
        : "Sites, sistemas de pedidos, ERP/CRM, agendamento e software sob medida pela SUDRA Technologies."
    );
  }
  const ogLocale = document.querySelector('meta[property="og:locale"]');
  if (ogLocale) ogLocale.setAttribute("content", locale === "en" ? "en_US" : "pt_BR");
  const twTitle = document.querySelector('meta[name="twitter:title"]');
  if (twTitle) twTitle.setAttribute("content", t("meta.title", locale));
  const twDesc = document.querySelector('meta[name="twitter:description"]');
  if (twDesc) {
    twDesc.setAttribute(
      "content",
      locale === "en"
        ? "Websites, order systems, ERP/CRM, scheduling, and custom software by SUDRA Technologies."
        : "Sites, sistemas de pedidos, ERP/CRM, agendamento e software sob medida pela SUDRA Technologies."
    );
  }
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = t(key, locale);
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      el.placeholder = value;
    } else {
      el.textContent = value;
    }
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    el.setAttribute("aria-label", t(key, locale));
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.dataset.locale === locale;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", String(active));
  });
  updateThemeButtonLabel();
}

function setLocale(locale) {
  if (locale !== "pt" && locale !== "en") return;
  localStorage.setItem(LOCALE_KEY, locale);
  applyI18n(locale);
  document.dispatchEvent(new CustomEvent("localechange", { detail: { locale } }));
}

function getTheme() {
  const stored = localStorage.getItem(THEME_KEY);
  if (stored === "light" || stored === "dark") return stored;
  if (window.matchMedia("(prefers-color-scheme: dark)").matches) return "dark";
  return "light";
}

function applyPartnerLogos(theme) {
  const mode = theme === "dark" ? "dark" : "light";
  document.querySelectorAll(".theme-logo[data-logo]").forEach((img) => {
    const pair = LOGO_SRC[img.getAttribute("data-logo")];
    if (pair) img.src = pair[mode];
  });
}

function applyTheme(theme) {
  document.documentElement.setAttribute("data-theme", theme);
  updateThemeButtonLabel();
  applyPartnerLogos(theme);
}

function updateThemeButtonLabel() {
  const btn = document.getElementById("theme-toggle");
  if (!btn) return;
  const theme = document.documentElement.getAttribute("data-theme") || "light";
  const key = theme === "dark" ? "theme.toLight" : "theme.toDark";
  btn.setAttribute("aria-label", t(key));
  btn.setAttribute("title", t(key));
}

function setTheme(theme) {
  const next = theme === "dark" ? "dark" : "light";
  localStorage.setItem(THEME_KEY, next);
  applyTheme(next);
}

function toggleTheme() {
  const current = document.documentElement.getAttribute("data-theme") || getTheme();
  setTheme(current === "dark" ? "light" : "dark");
}

function initI18n() {
  applyTheme(getTheme());
  applyI18n(getLocale());
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => setLocale(btn.dataset.locale));
  });
  document.getElementById("theme-toggle")?.addEventListener("click", toggleTheme);
}

window.PortfolioI18n = {
  getLocale,
  setLocale,
  t,
  applyI18n,
  initI18n,
  getTheme,
  setTheme,
  toggleTheme,
};
